/**
 * Render every Forecourt email to HTML + plain text for Resend.
 *   npx tsx scripts/render-emails.tsx
 * Writes src/emails/dist/<name>.html and .txt, and the confirm email module
 * the newsletter server uses. Sends nothing.
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { render } from "@react-email/render";
import { createElement } from "react";
import { Email } from "../src/emails/layout.tsx";
import { EMAILS } from "../src/emails/content.ts";

const out = "src/emails/dist";
mkdirSync(out, { recursive: true });
const BAD = /[\u2013\u2014\u00b7]|glass/i;
// Templates the launch sequence and the monthly broadcast draft read at runtime.
const LIST_EMAILS = new Set(["launch-2a", "launch-2b", "launch-2c", "launch-2d", "monthly"]);
const listOut: Record<string, { subject: string; html: string; text: string }> = {};

for (const doc of EMAILS) {
  const html = await render(createElement(Email, { doc }), { pretty: false });
  const txtPath = `src/emails/text/${doc.name}.txt`;
  const text = existsSync(txtPath) ? readFileSync(txtPath, "utf8") : "";
  for (const [k, v] of [["html", html], ["text", text], ["subject", doc.subject]] as const) {
    if (BAD.test(v)) throw new Error(`${doc.name} ${k}: dash, middle dot or banned word`);
  }
  // No [BRACKET] tokens anywhere. Merge tags only where intended.
  const allowed = doc.name === "monthly" ? null : new Set(["UNSUBSCRIBE_URL", "CONFIRM_URL"]);
  for (const [k, v] of [["html", html], ["text", text]] as const) {
    if (/\[[A-Z][A-Z0-9_: ]+\]/.test(v)) throw new Error(`${doc.name} ${k}: [PLACEHOLDER] left`);
    if (/FIRST_NAME/.test(v)) throw new Error(`${doc.name} ${k}: name tag left`);
    for (const m of v.matchAll(/\{\{([A-Z0-9_]+)\}\}/g)) if (allowed && !allowed.has(m[1])) throw new Error(`${doc.name} ${k}: unexpected {{${m[1]}}}`);
  }
  if (doc.footer !== "confirm" && !html.includes('href="{{UNSUBSCRIBE_URL}}"')) throw new Error(`${doc.name}: no unsubscribe link`);
  if (!doc.subject.startsWith("Forecourt: ")) throw new Error(`${doc.name}: subject prefix`);
  writeFileSync(`${out}/${doc.name}.html`, html);
  if (text) writeFileSync(`${out}/${doc.name}.txt`, text);
  console.log(`${doc.name}: ${(Buffer.byteLength(html) / 1024).toFixed(1)} KB html`);
  if (LIST_EMAILS.has(doc.name)) listOut[doc.name] = { subject: doc.subject, html, text };
  if (doc.name === "confirm") {
    writeFileSync(
      "src/lib/email/newsletter-confirm.generated.ts",
      `// Generated by scripts/render-emails.tsx. Do not edit.\n// Placeholders: {{CONFIRM_URL}}, [UNSUBSCRIBE_LINK].\nexport const CONFIRM_HTML = ${JSON.stringify(html)};\n`,
    );
  }
}

writeFileSync(
  "src/lib/email/newsletter-list.generated.ts",
  `// Generated by scripts/render-emails.tsx. Do not edit.\n// Placeholders: {{UNSUBSCRIBE_URL}} everywhere, plus the monthly editorial {{SLOTS}}.\nexport const LIST_EMAILS: Record<"launch-2a" | "launch-2b" | "launch-2c" | "launch-2d" | "monthly", { subject: string; html: string; text: string }> = ${JSON.stringify(listOut, null, 2)};\n`,
);
