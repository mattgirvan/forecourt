/**
 * Render every Forecourt email to HTML + plain text for Resend.
 *   npx tsx scripts/render-emails.tsx
 * Writes src/emails/dist/<name>.html and .txt, and the confirm email module
 * the newsletter server uses. Sends nothing.
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { render } from "@react-email/render";
import { createElement } from "react";
import { Email } from "../src/emails/layout.tsx";
import { EMAILS } from "../src/emails/content.ts";

const out = "src/emails/dist";
mkdirSync(out, { recursive: true });
const BAD = /[\u2013\u2014\u00b7]|glass/i;

for (const doc of EMAILS) {
  const html = await render(createElement(Email, { doc }), { pretty: false });
  const txtPath = `src/emails/text/${doc.name}.txt`;
  const text = existsSync(txtPath) ? readFileSync(txtPath, "utf8") : "";
  for (const [k, v] of [["html", html], ["text", text], ["subject", doc.subject]] as const) {
    if (BAD.test(v)) throw new Error(`${doc.name} ${k}: dash, middle dot or banned word`);
  }
  if (!doc.subject.startsWith("Forecourt: ")) throw new Error(`${doc.name}: subject prefix`);
  writeFileSync(`${out}/${doc.name}.html`, html);
  if (text) writeFileSync(`${out}/${doc.name}.txt`, text);
  console.log(`${doc.name}: ${(Buffer.byteLength(html) / 1024).toFixed(1)} KB html`);
  if (doc.name === "confirm") {
    writeFileSync(
      "src/lib/email/newsletter-confirm.generated.ts",
      `// Generated by scripts/render-emails.tsx. Do not edit.\n// Placeholders: {{CONFIRM_URL}}, [UNSUBSCRIBE_LINK].\nexport const CONFIRM_HTML = ${JSON.stringify(html)};\n`,
    );
  }
}
